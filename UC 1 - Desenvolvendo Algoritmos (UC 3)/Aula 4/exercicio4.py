#Revisão 4: Crie um programa que pede os 3 lados de um triângulo e calcule o seu perímetro:

lado1 = float(input("Digite o lado 1 do triângulo:"))
lado2 = float(input("Digite o lado 2 do triângulo:"))
lado3 = float(input("Digite o lado 3 do triângulo:"))

perimetro = lado1 + lado2 + lado3

print(f"O perímetro do triângulo é: {perimetro} metros")
